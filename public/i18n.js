const ERA_KEYS = { 'Me da igual': 'era.any', 'Lo más nuevo': 'era.new', '2020s': 'era.2020s', '2010s': 'era.2010s', '2000s': 'era.2000s', '90s': 'era.90s', 'Clásicos': 'era.classics' };

function detect() {
  const fromUrl = new URLSearchParams(location.search).get('lang');
  let saved = null;
  try { saved = localStorage.getItem('vibelist.lang'); } catch {}
  for (const c of [fromUrl, saved, ...(navigator.languages || [navigator.language])]) {
    const code = String(c || '').slice(0, 2).toLowerCase();
    if (LANGS[code]) return code;
  }
  return 'en';
}

export let lang = detect();

export function setLang(code) {
  if (!LANGS[code]) return;
  lang = code;
  try { localStorage.setItem('vibelist.lang', code); } catch {}
}

/** Traduce una clave, con {variables}. Cae al inglés si falta. */
export function t(key, vars = {}) {
  const s = D[lang]?.[key] ?? D.en[key] ?? key;
  return typeof s === 'string' ? s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`)) : s;
}

export const genreLabel = (k) => (lang === 'es' ? k : D[lang]?.genres?.[k] || D.en.genres[k] || k);
export const moodLabel = (k) => (lang === 'es' ? k : D[lang]?.moods?.[k] || D.en.moods[k] || k);
export const eraLabel = (k) => t(ERA_KEYS[k] || 'era.any');
export const examples = () => D[lang]?.examples || D.en.examples;

/** Rellena el HTML: data-i18n (texto), data-i18n-ph (placeholder), data-i18n-aria (aria-label). */
export function applyStatic(root = document) {
  document.documentElement.lang = lang;
  document.title = t('meta.title');
  document.querySelector('meta[name="description"]')?.setAttribute('content', t('meta.desc'));
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
}
